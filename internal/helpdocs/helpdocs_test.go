func load(t *testing.T) *Docs {
	t.Helper()
	d, err := Load(greenlens.Docs(), []string{"es"})
	if err != nil {
		t.Fatal(err)
	}
	return d
}

func TestIndex(t *testing.T) {
	d := load(t)
	for _, lang := range []string{"en", "es"} {
		idx := d.Index(lang)
		if len(idx) < 20 {
			t.Fatalf("%s: %d pages", lang, len(idx))
		}
		// Sections come in order, each with its own page first.
		last := -1
		for i, p := range idx {
			s := sectionIndex(p.Section)
			if s < last {
				t.Fatalf("%s: %s out of order", lang, p.Path)
			}
			if s != last && p.Section != "" && p.Path != p.Section {
				t.Errorf("%s: section %s starts with %s", lang, p.Section, idx[i].Path)
			}
			last = s
		}
	}
	es := d.Index("es")
	found := false
	for _, p := range es {
		if p.Path == "guides/http-api" && strings.Contains(p.Title, "tokens de acceso") {
			found = true
		}
	}
	if !found {
		t.Error("the Spanish index lacks the Spanish guide")
	}
}

func sectionIndex(s string) int {
	for i, x := range Sections {
		if x == s {
			return i
		}
	}
	return -1
}

func TestRenderRewritesLinks(t *testing.T) {
	d := load(t)
	title, html, ok := d.Render("en", "guides/language")
	if !ok || title == "" {
		t.Fatal("page not found")
	}
	if !strings.Contains(html, `href="#/help/reference/errors?anchor=gl0008"`) {
		t.Errorf("cross-page link not rewritten:\n%s", html)
	}
	_, api, _ := d.Render("es", "reference/api")
	if !strings.Contains(api, `href="#/help/reference/api?anchor=error"`) || !strings.Contains(api, `id="error"`) {
		t.Error("in-page anchors do not work")
	}
	if strings.Contains(api, "Generated by") {
		t.Error("the front matter is rendered")
	}
	if _, _, ok := d.Render("es", "no/such/page"); ok {
		t.Error("a missing page was rendered")
	}
}

func TestRenderIsSafe(t *testing.T) {
	fsys := fstest.MapFS{
		"guides/x.md":    {Data: []byte("---\ntitle: \"X\"\n---\n\nText <script>alert(1)</script> [site](https://example.com/) [y](../y/) [missing](../nope/)\n\n<img src=x onerror=alert(1)>\n")},
		"guides/y.md":    {Data: []byte("# Y\n")},
		"es/guides/y.md": {Data: []byte("# Y es\n")},
	}
	d, err := Load(fsys, []string{"es"})
	if err != nil {
		t.Fatal(err)
	}
	_, html, ok := d.Render("en", "guides/x")
	if !ok {
		t.Fatal("not rendered")
	}
	for _, bad := range []string{"<script", "onerror", "<img"} {
		if strings.Contains(html, bad) {
			t.Errorf("raw HTML kept: %s", html)
		}
	}
	if !strings.Contains(html, `href="https://example.com/" rel="noreferrer"`) || !strings.Contains(html, `href="#/help/guides/y"`) || !strings.Contains(html, `href="#/help/guides/x"`) {
		t.Errorf("links: %s", html)
	}
	// A page without a translation falls back to English.
	if title, _, ok := d.Render("es", "guides/x"); !ok || title != "X" {
		t.Errorf("fallback: %q %v", title, ok)
	}
}

func TestSearch(t *testing.T) {
	d := load(t)
	res := d.Search("en", "bearer token")
	if len(res) == 0 || res[0].Path != "guides/http-api" || !strings.Contains(strings.ToLower(res[0].Snippet), "bearer") {
		t.Fatalf("search: %+v", res)
	}
	if res := d.Search("es", "token de acceso"); len(res) == 0 {
		t.Error("no Spanish result")
	}
	if res := d.Search("en", "  "); len(res) != 0 {
		t.Error("an empty search matched")
	}
	if res := d.Search("en", "zzqqxx"); len(res) != 0 {
		t.Error("a nonsense word matched")
	}
}
