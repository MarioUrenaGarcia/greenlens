// Command gen-docs writes the reference pages that are derived from the
// code, in every supported language, so they cannot drift from the binary.
// Run it from the repository root with "make docs".
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/MarioUrenaGarcia/greenlens/internal/help"
	"github.com/MarioUrenaGarcia/greenlens/internal/i18n"
)

type page struct {
	title, intro, code, message, cause, fix, exit string
}

var pages = map[string]page{
	"en": {
		title:   "Error codes",
		intro:   "Every error that GreenLens reports has a stable code, a one-line message, the cause and a suggested fix. Text in braces is replaced with the actual values, such as the name of the command.",
		code:    "Code",
		message: "Message",
		cause:   "Cause",
		fix:     "Fix",
		exit:    "Exit code",
	},
	"es": {
		title:   "Códigos de error",
		intro:   "Cada error que reporta GreenLens tiene un código estable, un mensaje de una línea, la causa y una solución sugerida. El texto entre llaves se reemplaza por los valores reales, como el nombre del comando.",
		code:    "Código",
		message: "Mensaje",
		cause:   "Causa",
		fix:     "Solución",
		exit:    "Código de salida",
	},
}

func main() {
	root := flag.String("root", "docs", "documentation directory")
	flag.Parse()
	if err := run(*root); err != nil {
		fmt.Fprintln(os.Stderr, "gen-docs:", err)
		os.Exit(1)
	}
}

func run(root string) error {
	codes := help.Codes()
	slices.Sort(codes)
	for _, lang := range i18n.Supported {
		l, err := i18n.New(lang)
		if err != nil {
			return err
		}
		p := pages[lang]
		dir := filepath.Join(root, "reference")
		if lang != i18n.Default {
			dir = filepath.Join(root, lang, "reference")
		}
		if err := os.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // documentation tree
			return err
		}
		var b strings.Builder
		b.WriteString("---\n# Generated by \"make docs\" from internal/help and the translation catalogs.\n")
		fmt.Fprintf(&b, "title: %q\nweight: 20\n---\n\n", p.title)
		b.WriteString(p.intro + "\n\n")
		fmt.Fprintf(&b, "| %s | %s | %s |\n|---|---|---|\n", p.code, p.message, p.exit)
		for _, c := range codes {
			e := help.New(c)
			fmt.Fprintf(&b, "| [%s](#%s) | %s | %d |\n", c, strings.ToLower(string(c)), escape(e.Message(l)), e.ExitCode())
		}
		for _, c := range codes {
			e := help.New(c)
			fmt.Fprintf(&b, "\n## %s\n\n", c)
			fmt.Fprintf(&b, "- **%s:** %s\n", p.message, escape(e.Message(l)))
			fmt.Fprintf(&b, "- **%s:** %s\n", p.cause, escape(e.Cause(l)))
			fmt.Fprintf(&b, "- **%s:** %s\n", p.fix, escape(e.Fix(l)))
			fmt.Fprintf(&b, "- **%s:** %d\n", p.exit, e.ExitCode())
		}
		if err := os.WriteFile(filepath.Join(dir, "errors.md"), []byte(b.String()), 0o644); err != nil { //nolint:gosec // documentation file
			return err
		}
	}
	return nil
}

// escape keeps placeholders and quotes readable in Markdown tables.
func escape(s string) string {
	return strings.NewReplacer("|", "\\|", "{", "`{", "}", "}`", "<", "&lt;", ">", "&gt;").Replace(s)
}
